function Publish-CodexDesktopBridge {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][string]$RepositoryRoot,
        [Parameter(Mandatory = $true)][string]$PackageRoot,
        [Parameter(Mandatory = $true)][string]$WorkspaceDir,
        [string]$DotnetPath = 'dotnet'
    )
    $ErrorActionPreference = 'Stop'
    $project = Join-Path $RepositoryRoot 'tools/CodexDesktopBridge/CodexDesktopBridge.csproj'
    $published = Join-Path $WorkspaceDir 'desktop-bridge-publish'
    & $DotnetPath publish $project --configuration Release --runtime win-x64 --self-contained true `
        -p:PublishSingleFile=true -p:DebugType=none -p:DebugSymbols=false --output $published | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'Desktop bridge publication failed.' }
    $resources = Join-Path $PackageRoot 'codex-resources'
    $destination = Join-Path $resources 'desktop-bridge'
    New-Item -ItemType Directory -Path $destination -Force | Out-Null
    $executable = Join-Path $destination 'codex-desktop-bridge.exe'
    Copy-Item -LiteralPath (Join-Path $published 'codex-desktop-bridge.exe') -Destination $executable
    foreach ($name in @('Install-CodexDesktopBridge.ps1', 'Start-CodexDesktopWithBridge.ps1')) {
        Copy-Item -LiteralPath (Join-Path $RepositoryRoot "scripts/$name") -Destination (Join-Path $resources $name)
    }
    Copy-Item -LiteralPath (Join-Path $RepositoryRoot 'docs/desktop-browser-bridge.md') -Destination $resources
    $checks = Join-Path $PackageRoot 'desktop-bridge-checks.json'
    & python (Join-Path $RepositoryRoot 'scripts/test-desktop-bridge.py') --bridge $executable `
        --cli (Join-Path $PackageRoot 'bin/codex.exe') --output $checks | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'Packaged desktop bridge transport checks failed.' }
    $report = Get-Content -LiteralPath $checks -Raw | ConvertFrom-Json
    return [ordered]@{
        included = $true
        opt_in = $true
        executable = 'codex-resources/desktop-bridge/codex-desktop-bridge.exe'
        sha256 = (Get-FileHash -LiteralPath $executable -Algorithm SHA256).Hash.ToLowerInvariant()
        installer = 'codex-resources/Install-CodexDesktopBridge.ps1'
        transport_checks_passed = $report.passed
        browser_authorization = 'Provided by the desktop host; not generated by the bridge'
    }
}
